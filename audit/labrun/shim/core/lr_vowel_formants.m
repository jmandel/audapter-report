function F = lr_vowel_formants(v, male)
% Hillenbrand et al. (1995) average F1-F3 (Hz) for men / women.
M = struct('IY', [342 2322 3000], 'IH', [427 2034 2684], 'EY', [476 2089 2691], 'EH', [580 1799 2605], 'AE', [588 1952 2601], ...
  'AH', [623 1200 2550], 'AA', [768 1333 2522], 'AO', [652 997 2538], 'OW', [497 910 2459], 'UH', [469 1122 2434], 'UW', [378 997 2343], 'ER', [474 1379 1710]);
W = struct('IY', [437 2761 3372], 'IH', [483 2365 3053], 'EY', [536 2530 3047], 'EH', [731 2058 2979], 'AE', [669 2349 2972], ...
  'AH', [753 1426 2933], 'AA', [936 1551 2815], 'AO', [781 1136 2824], 'OW', [555 1035 2828], 'UH', [519 1225 2827], 'UW', [459 1105 2735], 'ER', [523 1588 1929]);
if ~isfield(M, v), v = 'AH'; end
if male, F = M.(v); else, F = W.(v); end
end
