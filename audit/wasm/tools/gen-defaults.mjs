// Generate web/audapter-defaults.mjs (compact) from testdata/defaults_{female,male}/defaults.json, which
// harness/oct/wasm_export.m recorded from the real blab AudapterIO('init', getAudapterDefaultParams(sex)).
import fs from 'node:fs';
const W = new URL('..', import.meta.url);
const out = {};
for (const sex of ['female', 'male']) {
  const m = JSON.parse(fs.readFileSync(new URL(`testdata/defaults_${sex}/defaults.json`, W)));
  out[sex] = m.cmds.filter(c => c.op === 'setParam').map(c => {
    let v = c.value;
    if (Array.isArray(v) && v.length > 8 && v.every(x => x === v[0])) v = { fill: v[0], n: v.length };
    return [c.name, v];
  });
}
fs.writeFileSync(new URL('web/audapter-defaults.mjs', W),
  '// GENERATED by tools/gen-defaults.mjs from blab AudapterIO(\'init\', getAudapterDefaultParams(sex)) (setParam order).\n' +
  '// Values {fill, n} are constant arrays of length n.\nexport default ' + JSON.stringify(out) + ';\n');
